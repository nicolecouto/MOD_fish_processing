% registry = MODsetup_metadata_field_registry()
%
% DESCRIPTION
%   The single source of truth for every deployment-tunable value this
%   repo currently knows how to read from setup.yml: where it lives in
%   setup.yml (yaml_section/yaml_key), where it lives in metadata
%   (metadata_path), what it's for, and what value it has historically
%   defaulted to. Consumed by MODsetup_validate_metadata.m (looks up each
%   requested name to know what to check/prompt for) and
%   MODsetup_write_yaml_value.m callers (to know which section/key to
%   write). MODsetup_read_yaml.m loops over it to read every parameter the
%   yml declares (yaml_section.yaml_key -> metadata_path) - only when
%   declared, never defaulted. MODsetup_preflight.m uses yaml_section to
%   decide which parameters a manifest needs, and
%   MODsetup_write_cruise_meta_data_template.m writes the cruise template
%   from it. suggested_default is the starting value shown in
%   MODsetup_prompt_value.m's popup and in that template - never applied
%   silently.
%
%   The 10 PROCESS.CHI entries, 6 of the 7 profile-picking entries
%   (modProcess_detect_profiles.m; profile_dir is validated in
%   MODprocess_single_L1_to_L2.m instead - it gates epsi spectra,
%   not profile detection), epsi_gap_factor
%   (modProcess_extract_profile.m), and fft_length/fft_segments_per_scan/
%   scan_overlap (mod_scan_get_spectra.m, mod_L2_tile_scans.m,
%   mod_scan_calc_chi_mle.m - scan_length is derived from the first two,
%   dof from fft_segments_per_scan alone, neither is its own entry) have
%   real MODsetup_validate_metadata.m call sites.
%   PROFILES.lowpass_sec/.ctd_gap_factor/.buffer_bins have a real call
%   site too (mod_L1_detect_profiling_direction.m), and
%   PROFILES.speedLim_scan_m_s (mod_L2_tile_scans.m). The 14 PROCESS.EPSILON
%   entries are mostly wired in as well, now that mod_scan_calc_epsilon.m
%   and its siblings exist (branch epsilon_processing, 2026-09-08):
%   epsilon_final_source (MODprocess_single_L1_to_L2.m); epsilon_kmin_obs
%   (mod_scan_calc_epsilon.m, and again in mod_scan_calc_epsilon_obs.m,
%   which it calls in turn); contam_freq_hz_shear/epsilon_stage1_kmin/
%   epsilon_stage1_kmax (mod_scan_calc_epsilon_obs.m); kmin_mle/
%   mle_start_search/mle_end_search (mod_scan_calc_epsilon_mle.m);
%   coherence_fmin_hz/coherence_fmax_hz (mod_scan_shear_accel_coherence.m);
%   oakey_lc_m (mod_scan_shear_volts_to_shear_spectrum.m). Only
%   qc_accel_method/.qc_accel_threshold/.qc_accel_nstd (profile-QC)
%   are still in the original situation: no MODsetup_validate_metadata.m
%   call site yet, because their consumer doesn't exist yet
%   (modProcess_L2_qc.m is "Not started" in PLAN.md Section 6.4) -
%   registered ahead of time, same as the epsilon
%   entries were, from a review of Jen's ASTRAL reprocessing fork so the
%   parameters those modules will need aren't lost before they're built.
%   See SESSION_LOG.md, 2026-09-02 and 2026-09-08.
%
% OUTPUTS
%   registry - struct array (1 x 57), one entry per value:
%     name              - short key used in MODsetup_validate_metadata.m's
%                          list_of_variables, e.g. 'kmin_obs'
%     yaml_section       - top-level setup.yml block, e.g. 'chi'
%     yaml_key           - key within that block, e.g. 'kmin_obs'
%     metadata_path      - cellstr of nested metadata field names, e.g.
%                          {'PROCESS','CHI','kmin_obs'}
%     description        - human-readable, shown in MODsetup_prompt_value.m
%     suggested_default  - this function's historical hardcoded value,
%                          shown as the prompt's starting value only
%
% CALLED BY
%   MODsetup_validate_metadata.m, MODsetup_read_yaml.m, MODsetup_preflight.m,
%   MODsetup_build_yaml.m, MODsetup_write_cruise_meta_data_template.m
%
% CALLS
%   (none)
%
% Multiscale Ocean Dynamics (MOD) Group, Scripps Institution of Oceanography

